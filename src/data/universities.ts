export const getUniversitiesByProvince = (province: string) => {
  return universities.filter((u) => u.province === province);
};

export const getUniversityById = (id: string) => {
  return universities.find((u) => u.id === id);
};

export const getProvinces = () => {
  return Array.from(new Set(universities.map((u) => u.province)));
};

export const searchUniversities = (query: string) => {
  const q = query.toLowerCase();
  return universities.filter(
    (u) =>
      u.name.toLowerCase().includes(q) ||
      u.specialties.some((s) => s.toLowerCase().includes(q)) ||
      u.city.toLowerCase().includes(q)
  );
};

// Helper for MapExplorer: group universities by city
export interface CityMarker {
  id: string;
  name: string;
  lat: number;
  lng: number;
  universities: University[];
}

export const getCitiesForMap = (): CityMarker[] => {
  const cityMap = new Map<string, CityMarker>();
  const cityCoordinates: Record<string, { lat: number; lng: number }> = {
    "Antananarivo": { lat: -18.8792, lng: 47.5079 },
    "Toamasina": { lat: -18.1492, lng: 49.4023 },
    "Fianarantsoa": { lat: -21.4417, lng: 47.0833 },
    "Mahajanga": { lat: -15.7167, lng: 46.3167 },
    "Toliara": { lat: -23.35, lng: 43.6667 },
    "Antsiranana": { lat: -12.2795, lng: 49.2913 },
    "Antsirabe": { lat: -19.8659, lng: 47.0333 },
    "Fénérive-Est": { lat: -17.3067, lng: 49.4167 },
    "Ambositra": { lat: -20.5133, lng: 47.1333 },
    "Ambalavao": { lat: -21.8167, lng: 46.65 },
    "Antsohihy": { lat: -14.6833, lng: 47.9833 },
    "Morondava": { lat: -20.2833, lng: 44.3167 },
    "Fort-Dauphin": { lat: -25.0356, lng: 46.9975 },
    "Sambava": { lat: -16.7667, lng: 49.9833 },
  };

  universities.forEach((uni) => {
    const cityKey = uni.city;
    const coords = cityCoordinates[cityKey] || cityCoordinates["Antananarivo"];

    if (!cityMap.has(cityKey)) {
      cityMap.set(cityKey, {
        id: cityKey.toLowerCase().replace(/\s+/g, "-"),
        name: cityKey,
        lat: coords.lat,
        lng: coords.lng,
        universities: [],
      });
    }

    cityMap.get(cityKey)!.universities.push(uni);
  });

  return Array.from(cityMap.values());
};
